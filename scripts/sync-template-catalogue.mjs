#!/usr/bin/env node
/**
 * Generates `server/src/data/templateCatalogue.json` from the client catalogue.
 *
 * The server needs to know every valid template id (for validation) and which
 * of them are premium (for entitlement checks). Keeping one source of truth
 * avoids the two lists drifting apart.
 *
 *   node scripts/sync-template-catalogue.mjs           # write the file
 *   node scripts/sync-template-catalogue.mjs --check   # fail if out of date
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const clientCatalogue = path.join(root, 'client/src/data/templateCatalogue.js');
const serverManifest = path.join(root, 'server/src/data/templateCatalogue.json');

const { TEMPLATE_ID_MANIFEST, TEMPLATE_COUNT, PREMIUM_TEMPLATE_COUNT, FREE_TEMPLATE_COUNT } = await import(
  clientCatalogue
);

if (PREMIUM_TEMPLATE_COUNT < 100) {
  console.error(`Refusing to sync: catalogue only has ${PREMIUM_TEMPLATE_COUNT} premium templates (minimum 100).`);
  process.exit(1);
}

const ids = new Set(TEMPLATE_ID_MANIFEST.map((entry) => entry.id));
if (ids.size !== TEMPLATE_ID_MANIFEST.length) {
  console.error('Refusing to sync: duplicate template ids found in the catalogue.');
  process.exit(1);
}

const payload = {
  $comment:
    'Generated by scripts/sync-template-catalogue.mjs from client/src/data/templateCatalogue.js. Do not edit by hand.',
  counts: { total: TEMPLATE_COUNT, premium: PREMIUM_TEMPLATE_COUNT, free: FREE_TEMPLATE_COUNT },
  templates: TEMPLATE_ID_MANIFEST,
};

const serialised = `${JSON.stringify(payload, null, 2)}\n`;

if (process.argv.includes('--check')) {
  const current = await fs.readFile(serverManifest, 'utf8').catch(() => '');
  if (current !== serialised) {
    console.error('Template manifest is out of date. Run: node scripts/sync-template-catalogue.mjs');
    process.exit(1);
  }
  console.log('Template manifest is in sync.');
  process.exit(0);
}

await fs.mkdir(path.dirname(serverManifest), { recursive: true });
await fs.writeFile(serverManifest, serialised, 'utf8');
console.log(
  `Wrote ${TEMPLATE_COUNT} templates (${PREMIUM_TEMPLATE_COUNT} premium, ${FREE_TEMPLATE_COUNT} free) to ${path.relative(root, serverManifest)}`
);
